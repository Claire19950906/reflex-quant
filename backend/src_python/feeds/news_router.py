def foreign_local_stat_reason(text: str) -> str:
    """别国本地统计数据 → 池外宏观理由；"" = 需要正常分析。"""
    country = _hit(text, FOREIGN_LOCAL_MARKETS)
    if not country:
        return ""
    if not _hit(text, LOCAL_STAT_WORDS):
        return ""
    if _hit(text, STRONG_ANCHORS):
        return ""
    return f"池外宏观（{country}本地数据）"



def _hit(text: str, words: Iterable[str]) -> str:
    up = text.upper()
    for w in words:
        if w.upper() in up:
            return w
    return ""


def _has_anchor(text: str) -> bool:
    """有没有"能落到五个品种上"的锚点：池内品种 / 宏观 / 地缘供给 / 交易所链上。"""
    return bool(_hit(text, POOL_KEYWORDS) or _hit(text, ANCHOR_EXTRA))


def pool_out_reason(title: str, content: str = "") -> str:
    """返回 "" = 需要正常分析；非空 = 池外，理由字符串。"""
    t = str(title or "").strip()
    c = str(content or "").strip()
    if not t and not c:
        return ""
    text = f"{t} {(c[:400] if c else '')}"

    # 0) v408 市场归属：别国本地统计数据先判池外。
    #    必须排在"命中池关键词就放行"之前 —— 否则「以色列CPI」会被 POOL_KEYWORDS
    #    里的 CPI 自己救回来。`NEWS_POOL_SCOPE=0` 可一键退回旧行为。
    if str(os.getenv("NEWS_POOL_SCOPE", "1")).strip() != "0":
        scope_reason = foreign_local_stat_reason(text)
        if scope_reason:
            return scope_reason

    # 1a) 显式非交易池市场**个股**代码 → 池外。
    #     v425：必须排在"池关键词放行"之前 —— 否则 [A股 600519] / [港股 00700]
    #     会被新增的"A股 / 沪指 / 港股"关键词救回来，把纯个股公告灌进 LLM。
    mkt = _NONPOOL_TICKER.search(text)
    if mkt:
        return f"池外个股（{mkt.group(1)}）"

    # 1) 命中交易池/宏观关键词 → 必须分析
    if _hit(text, POOL_KEYWORDS):
        return ""

    # 3b) v406：没有任何锚点 + 非交易类主体 → 池外（不进 LLM）
    #     与规则 3 的区别：3 需要"公司行为 + 公司主体"同时命中（A 股公告口径），
    #     3b 面向"产品发布 / 人事任免 / 司法 / 文体"这类永远落不到品种上的新闻。
    if not _has_anchor(text):
        nm = _hit(text, NONMARKET_ACTIONS)
        if nm:
            return f"非交易类主体（{nm}）"
        # 3c) 纯白名单开关：连"主体词"都没有也挡（默认关）
        if str(os.getenv("NEWS_POOL_WHITELIST", "0")).strip() == "1":
            return "无池内锚点"

    # 3) 必须是公司行为 + 公司主体
    action = _hit(text, COMPANY_ACTIONS)
    if not action:
        return ""
    entity = _hit(text, COMPANY_ENTITIES)
    if not entity and not _BRACKET.match(t) and not _NAME_COLON.match(t):
        return ""
    return f"池外个股（{action}）"


def route(title: str, content: str = "") -> dict:
    reason = pool_out_reason(title, content)
    return {"route": "pool_out" if reason else "analyze", "reason": reason}
